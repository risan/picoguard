// Command agh-flow runs a pinned AdGuard Home binary against a scripted fake
// upstream and records its replies.
//
// It is a development tool for generating golden files. It drives a GPL-3.0
// program and is never linked into picoguard.
//
// Full-flow mode records the whole reply for every query of a case file:
//
//	agh-flow -agh BINARY -case FILE -out FILE
//
// The case file has the sections [main] (one per list, in order), [user],
// [allow], [upstream] and [queries]. See tests/fixtures/golden/flow/flow.case.
//
// Decisions mode checks agh-oracle against the real binary. The upstream
// answers every question with a TTL-300 record, so a reply with another TTL is
// AdGuard Home's own blocked reply, and the output has the agh-oracle form:
//
//	agh-flow -agh BINARY -list FILE... [-user FILE] [-allow FILE...] -q FILE -out FILE
package main

import (
	"bufio"
	"compress/gzip"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/miekg/dns"
)

// aghProcess is killed when the tool exits through fatal.
var aghProcess *os.Process

type caseFile struct {
	main     []string
	user     string
	allow    []string
	upstream string
	queries  []string
}

type multiFlag []string

func (m *multiFlag) String() string { return strings.Join(*m, ",") }

func (m *multiFlag) Set(v string) error {
	*m = append(*m, v)

	return nil
}

func main() {
	aghBin := flag.String("agh", "", "AdGuard Home binary")
	casePath := flag.String("case", "", "case file (full-flow mode)")
	outPath := flag.String("out", "", "output file")
	dnsPort := flag.Int("dns-port", 55353, "AdGuard Home DNS port")
	upPort := flag.Int("upstream-port", 55354, "fake upstream port")
	webPort := flag.Int("web-port", 55355, "AdGuard Home web port")
	var lists, allows multiFlag
	flag.Var(&lists, "list", "decisions mode: main list file (.gz allowed), repeatable")
	flag.Var(&allows, "allow", "decisions mode: allowlist file, repeatable")
	user := flag.String("user", "", "decisions mode: user rules file")
	queries := flag.String("q", "", "decisions mode: query file with name and type per line")
	flag.Parse()

	decisions := *queries != ""
	if *aghBin == "" || *outPath == "" || (*casePath == "") == !decisions {
		flag.Usage()
		os.Exit(2)
	}

	var cf caseFile
	if decisions {
		cf = caseFromFiles(lists, *user, allows, *queries)
	} else {
		cf = parseCase(*casePath)
	}

	stopUpstream := serveUpstream(*upPort, parseScript(cf.upstream), decisions)
	defer stopUpstream()

	dir, err := os.MkdirTemp("", "agh-flow-")
	check(err)
	defer os.RemoveAll(dir)

	writeWorkDir(dir, cf, *dnsPort, *upPort, *webPort)

	cmd := exec.Command(*aghBin,
		"-w", dir, "-c", filepath.Join(dir, "AdGuardHome.yaml"),
		"--no-check-update", "--no-permcheck")
	logFile, err := os.Create(filepath.Join(dir, "agh.log"))
	check(err)
	cmd.Stdout, cmd.Stderr = logFile, logFile
	check(cmd.Start())
	aghProcess = cmd.Process
	defer func() {
		_ = cmd.Process.Kill()
		_, _ = cmd.Process.Wait()
	}()

	waitReady(*webPort, len(cf.main)+len(cf.allow), dir)

	out, err := os.Create(*outPath)
	check(err)
	defer out.Close()

	w := bufio.NewWriter(out)
	defer w.Flush()

	if !decisions {
		fmt.Fprintf(w, "# Generated by tools/agh-flow from %s with AdGuard Home v0.107.79. Do not edit.\n", filepath.Base(*casePath))
	}

	client := &dns.Client{Net: "udp", Timeout: 5 * time.Second}
	for _, q := range cf.queries {
		fields := strings.Fields(q)
		if len(fields) != 2 {
			if decisions {
				continue
			}

			fatal("bad query %q", q)
		}

		qtype, ok := dns.StringToType[strings.ToUpper(fields[1])]
		if !ok {
			fatal("bad query type in %q", q)
		}

		if decisions && (qtype == dns.TypeANY || !isASCII(fields[0])) {
			continue
		}

		req := new(dns.Msg)
		req.SetQuestion(dns.Fqdn(fields[0]), qtype)
		req.RecursionDesired = true

		resp, _, err := client.Exchange(req, fmt.Sprintf("127.0.0.1:%d", *dnsPort))
		if err != nil {
			fatal("query %q: %v\n%s", q, err, tail(filepath.Join(dir, "agh.log")))
		}

		if decisions {
			fmt.Fprintf(w, "%s %s\n", q, decisionOf(resp))
		} else {
			writeReply(w, q, resp)
		}
	}
}

// decisionOf classifies a reply in the agh-oracle output form.
func decisionOf(resp *dns.Msg) string {
	var ips []string
	blocked := len(resp.Answer) == 0 && len(resp.Ns) == 0
	for _, rr := range resp.Answer {
		if rr.Header().Ttl != passthroughTTL {
			blocked = true
		}

		switch rr := rr.(type) {
		case *dns.A:
			ips = append(ips, rr.A.String())
		case *dns.AAAA:
			if v4 := rr.AAAA.To4(); v4 != nil {
				ips = append(ips, "::ffff:"+v4.String())
			} else {
				ips = append(ips, rr.AAAA.String())
			}
		}
	}

	for _, rr := range resp.Ns {
		if rr.Header().Ttl != passthroughTTL {
			blocked = true
		}
	}

	switch {
	case !blocked:
		return "pass -"
	case len(ips) > 0:
		return "block " + strings.Join(ips, ",")
	case len(resp.Ns) > 0:
		return "block nodata"
	default:
		return "block empty"
	}
}

func caseFromFiles(lists []string, user string, allows []string, queries string) (cf caseFile) {
	for _, p := range lists {
		cf.main = append(cf.main, string(readMaybeGz(p)))
	}

	for _, p := range allows {
		cf.allow = append(cf.allow, string(readMaybeGz(p)))
	}

	if user != "" {
		cf.user = string(readMaybeGz(user))
	}

	for _, line := range strings.Split(string(readMaybeGz(queries)), "\n") {
		if t := strings.TrimSpace(line); t != "" && !strings.HasPrefix(t, "#") {
			cf.queries = append(cf.queries, t)
		}
	}

	return cf
}

func readMaybeGz(path string) []byte {
	f, err := os.Open(path)
	check(err)
	defer f.Close()

	var r io.Reader = f
	if strings.HasSuffix(path, ".gz") {
		gz, err := gzip.NewReader(f)
		check(err)
		defer gz.Close()

		r = gz
	}

	data, err := io.ReadAll(r)
	check(err)

	return data
}

func writeReply(w io.Writer, q string, resp *dns.Msg) {
	fmt.Fprintf(w, "Q %s\n", q)
	fmt.Fprintf(w, "rcode %s flags%s\n", dns.RcodeToString[resp.Rcode], flags(resp))
	for _, rr := range resp.Answer {
		fmt.Fprintf(w, "an %s\n", rrText(rr))
	}

	for _, rr := range resp.Ns {
		fmt.Fprintf(w, "ns %s\n", rrText(rr))
	}

	for _, rr := range resp.Extra {
		if rr.Header().Rrtype != dns.TypeOPT {
			fmt.Fprintf(w, "ar %s\n", rrText(rr))
		}
	}

	fmt.Fprintln(w)
}

func flags(m *dns.Msg) (s string) {
	for _, f := range []struct {
		name string
		set  bool
	}{
		{"qr", m.Response}, {"aa", m.Authoritative}, {"tc", m.Truncated},
		{"rd", m.RecursionDesired}, {"ra", m.RecursionAvailable},
		{"ad", m.AuthenticatedData}, {"cd", m.CheckingDisabled},
	} {
		if f.set {
			s += " " + f.name
		}
	}

	return s
}

func rrText(rr dns.RR) string {
	h := rr.Header()
	rdata := strings.TrimPrefix(rr.String(), h.String())

	return fmt.Sprintf("%s %d %s %s", h.Name, h.Ttl, dns.TypeToString[h.Rrtype], strings.TrimSpace(rdata))
}

func parseCase(path string) (cf caseFile) {
	f, err := os.Open(path)
	check(err)
	defer f.Close()

	var section string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 1<<16), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		switch line {
		case "[main]":
			cf.main = append(cf.main, "")
			section = "main"
		case "[allow]":
			cf.allow = append(cf.allow, "")
			section = "allow"
		case "[user]", "[upstream]", "[queries]":
			section = strings.Trim(line, "[]")
		default:
			switch section {
			case "main":
				cf.main[len(cf.main)-1] += line + "\n"
			case "allow":
				cf.allow[len(cf.allow)-1] += line + "\n"
			case "user":
				cf.user += line + "\n"
			case "upstream":
				cf.upstream += line + "\n"
			case "queries":
				if t := strings.TrimSpace(line); t != "" && !strings.HasPrefix(t, "#") {
					cf.queries = append(cf.queries, t)
				}
			}
		}
	}

	check(sc.Err())

	return cf
}

// writeWorkDir lays out an AdGuard Home working directory: the filter lists
// are placed where it keeps downloaded filters (data/filters/<id>.txt), so it
// reads exactly the given text.
func writeWorkDir(dir string, cf caseFile, dnsPort, upPort, webPort int) {
	filters := filepath.Join(dir, "data", "filters")
	check(os.MkdirAll(filters, 0o755))

	var b strings.Builder
	fmt.Fprintf(&b, `http:
  address: 127.0.0.1:%d
users: []
dns:
  bind_hosts: [127.0.0.1]
  port: %d
  ratelimit: 0
  refuse_any: true
  upstream_dns: ["127.0.0.1:%d"]
  bootstrap_dns: ["127.0.0.1:%d"]
  upstream_mode: load_balance
  blocked_hosts: [version.bind, id.server, hostname.bind]
  cache_enabled: false
  cache_size: 0
  enable_dnssec: false
  use_private_ptr_resolvers: false
  hostsfile_enabled: false
  handle_ddr: false
querylog: {enabled: false, file_enabled: false}
statistics: {enabled: false}
filters:
`, webPort, dnsPort, upPort, upPort)

	for i, text := range cf.main {
		id := i + 1
		check(os.WriteFile(filepath.Join(filters, fmt.Sprintf("%d.txt", id)), []byte(endWithNewline(text)), 0o644))
		fmt.Fprintf(&b, "  - {enabled: true, url: \"https://example.invalid/%d.txt\", name: \"list%d\", id: %d}\n", id, id, id)
	}

	b.WriteString("whitelist_filters:\n")
	for i, text := range cf.allow {
		id := 1000 + i + 1
		check(os.WriteFile(filepath.Join(filters, fmt.Sprintf("%d.txt", id)), []byte(endWithNewline(text)), 0o644))
		fmt.Fprintf(&b, "  - {enabled: true, url: \"https://example.invalid/%d.txt\", name: \"allow%d\", id: %d}\n", id, id, id)
	}

	b.WriteString("user_rules:\n")
	for _, line := range strings.Split(cf.user, "\n") {
		if strings.TrimSpace(line) == "" {
			continue
		}

		quoted, err := json.Marshal(line)
		check(err)
		fmt.Fprintf(&b, "  - %s\n", quoted)
	}

	b.WriteString(`filtering:
  blocking_mode: default
  blocked_response_ttl: 10
  filtering_enabled: true
  protection_enabled: true
  filters_update_interval: 8760
  safebrowsing_enabled: false
  parental_enabled: false
  rewrites: []
clients:
  runtime_sources: {whois: false, arp: false, rdns: false, dhcp: false, hosts: false}
  persistent: []
log: {enabled: true, verbose: true}
schema_version: 34
`)
	check(os.WriteFile(filepath.Join(dir, "AdGuardHome.yaml"), []byte(b.String()), 0o644))
}

// waitReady polls the status API until every list reports its rules loaded.
func waitReady(webPort, lists int, dir string) {
	type filter struct {
		RulesCount int `json:"rules_count"`
	}

	deadline := time.Now().Add(120 * time.Second)
	url := fmt.Sprintf("http://127.0.0.1:%d/control/filtering/status", webPort)
	for time.Now().Before(deadline) {
		resp, err := http.Get(url)
		if err == nil {
			var st struct {
				Filters   []filter `json:"filters"`
				Whitelist []filter `json:"whitelist_filters"`
			}
			err = json.NewDecoder(resp.Body).Decode(&st)
			resp.Body.Close()
			if err == nil && len(st.Filters)+len(st.Whitelist) == lists {
				ready := true
				for _, f := range append(st.Filters, st.Whitelist...) {
					ready = ready && f.RulesCount > 0
				}

				if ready {
					time.Sleep(500 * time.Millisecond)

					return
				}
			}
		}

		time.Sleep(200 * time.Millisecond)
	}

	fatal("AdGuard Home did not become ready\n%s", tail(filepath.Join(dir, "agh.log")))
}

func tail(path string) string {
	data, _ := os.ReadFile(path)
	lines := strings.Split(string(data), "\n")
	if len(lines) > 40 {
		lines = lines[len(lines)-40:]
	}

	return strings.Join(lines, "\n")
}

func check(err error) {
	if err != nil {
		fatal("%v", err)
	}
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "agh-flow: "+format+"\n", args...)
	if aghProcess != nil {
		_ = aghProcess.Kill()
	}

	os.Exit(1)
}

// endWithNewline mirrors the filter files AdGuard Home writes itself. A rule on a
// last line without a line feed cannot be read back from a file-backed list, which
// is a property of the file layout and not of rule matching.
func endWithNewline(s string) string {
	if s != "" && !strings.HasSuffix(s, "\n") {
		return s + "\n"
	}

	return s
}

func isASCII(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] >= 0x80 {
			return false
		}
	}

	return true
}
